// THE TYPEFACE DECISION, recorded because the task asked for it to be.
//
// The real Cre8 Visions proposals are set in Georgia for display and Arial for
// body. Neither is redistributable, so neither can be committed here. Bree was
// asked and left the substitute to us (2026-09-18, #general).
//
//   Display  Georgia -> Gelasio. A Georgia-metric open face under the SIL Open
//            Font Licence — same large x-height, same sturdy weight, and the
//            same oldstyle figures Georgia is known for. Times, which pdf-lib
//            offers as standard, is none of those things and was the single
//            biggest visual difference from the real documents.
//   Body     Arial -> Helvetica, unchanged, and deliberately NOT embedded.
//            Helvetica is what Arial was drawn to match metrically, it is one
//            of pdf-lib's standard fonts, and it therefore costs zero bytes.
//
// There is precedent: the Aviya proposal already sent to a client was exported
// through LibreOffice and is in substitute faces already.
//
// WHY THE BYTES ARE IN A .ts FILE. Deploys here go through Lovable, which
// ships `_shared/` alongside the functions it deploys. A `.ttf` read off disk
// at runtime would be shipped only if that pipeline happened to include
// non-code files, and if it did not, font embedding would fail *silently* and
// every proposal would quietly go back to Times. Base64 in a module is part of
// the module graph, so it cannot be dropped without the import breaking loudly.
//
// Size is why this is affordable: the upstream variable fonts are 168K and
// 174K. Each is pinned to wght=400 and subset to Latin-1 plus typographic
// punctuation and currency, which takes the pair to 59K before encoding.
// Regenerate with fontTools:
//
//   python3 -m fontTools.varLib.instancer Gelasio[wght].ttf wght=400 -o r.ttf
//   python3 -m fontTools.subset r.ttf --layout-features="kern,liga,dlig" \
//     --unicodes="U+0020-007E,U+00A0-00FF,U+2010-2015,U+2018-201F,U+2020-2022,\
//     U+2026,U+2030,U+2039-203A,U+20AC,U+2122,U+00A3,U+00A5"
